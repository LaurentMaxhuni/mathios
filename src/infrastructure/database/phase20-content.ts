function gradeIdForNumber(grade: number): string {
  if (grade <= 12) return `grade-${grade}`;
  if (grade === 13) return "grade-university-foundations";
  if (grade === 14) return "grade-advanced";
  return "grade-olympiad";
}

function gradeIdsBetween(minimumGrade: number, maximumGrade: number): string[] {
  const grades = Array.from({ length: 7 }, (_, index) => index + 6).filter(
    (grade) => grade >= minimumGrade && grade <= maximumGrade,
  );
  for (const specialGrade of [13, 14, 15]) {
    if (specialGrade >= minimumGrade && specialGrade <= maximumGrade) grades.push(specialGrade);
  }
  return grades.map(gradeIdForNumber);
}

