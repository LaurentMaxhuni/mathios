const prerequisite = (subject: Phase20Subject, slug: string): string => `${subject}:${slug}`;

function topic(
  subjectSlug: Phase20Subject,
  slug: string,
  name: string,
  description: string,
  minimumGrade: number,
  maximumGrade: number,
  difficulty: Phase20Difficulty,
  formula: string,
  formulaLabel: string,
  workedExample: string,
  application: string,
  misconception: string,
  prerequisiteKeys: readonly string[] = [],
): Phase20Topic {
  return {
    key: `${subjectSlug}:${slug}`,
    slug,
    name,
    subjectSlug,
    domainId: `domain-${slug}`,
    description,
    minimumGrade,
    maximumGrade,
    difficulty,
    prerequisiteKeys,
    formula,
    formulaLabel,
    workedExample,
    application,
    misconception,
    sourceAttribution:
      "Mathios Phase 20 reference package; a curriculum-aligned synthesis for local educational use. Educators should review local standards and primary sources before external publication.",
  };
}

