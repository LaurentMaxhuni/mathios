function phase20RoadmapEdgeId(source: Phase20Topic, target: Phase20Topic): string {
  return `roadmap-edge-phase20-${source.subjectSlug}-${source.slug}-${target.subjectSlug}-${target.slug}`;
}

export const phase20RoadmapEdgeSeed = (() => {
  const nodesByKey = new Map(phase20TopicSeed.map((topic) => [topic.key, topic]));
  const edges: Array<{
    id: string;
    roadmapId: string;
    sourceNodeId: string;
    targetNodeId: string;
    type: "requires" | "recommended" | "optional";
    sortOrder: number;
  }> = [];
  const seen = new Set<string>();

  const addEdge = (
    source: Phase20Topic,
    target: Phase20Topic,
    type: "requires" | "recommended" | "optional",
  ) => {
    const id = phase20RoadmapEdgeId(source, target);
    if (seen.has(id)) return;
    seen.add(id);
    edges.push({
      id,
      roadmapId: phase20RoadmapId,
      sourceNodeId: phase20RoadmapNodeId(source),
      targetNodeId: phase20RoadmapNodeId(target),
      type,
      sortOrder: edges.length,
    });
  };

  for (const topic of phase20TopicSeed) {
    for (const prerequisiteKey of topic.prerequisiteKeys) {
      const prerequisiteTopic = nodesByKey.get(prerequisiteKey);
      if (prerequisiteTopic) addEdge(prerequisiteTopic, topic, "requires");
    }
    if (topic.slug.startsWith("olympiad")) {
      const previous = [...phase20TopicSeed]
        .reverse()
        .find(
          (candidate) => candidate.subjectSlug === topic.subjectSlug && candidate.key !== topic.key,
        );
      if (previous) addEdge(previous, topic, "optional");
    }
  }
  return edges;
})();

