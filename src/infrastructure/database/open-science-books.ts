function courseId(book: OpenScienceBook): string {
  return `course-open-science-${book.id}`;
}

function moduleId(book: OpenScienceBook): string {
  return `module-open-science-${book.id}`;
}

function lessonId(book: OpenScienceBook): string {
  return `lesson-open-science-${book.id}`;
}

function sectionId(book: OpenScienceBook, key: string): string {
  return `section-open-science-${book.id}-${key}`;
}

function blockId(book: OpenScienceBook, key: string): string {
  return `block-open-science-${book.id}-${key}`;
}

function versionId(book: OpenScienceBook): string {
  return `lesson-version-open-science-${book.id}-1`;
}

function bookDifficulty(book: OpenScienceBook): "balanced" | "challenging" {
  const advancedTitle =
    /advanced|abstract|analysis|astronomy|computational|complex|differential|electromagnet|graduate|mechanics|numerical|quantum|relativity|spectroscop|thermodynamics/i;
  return book.pageCount >= 650 || advancedTitle.test(book.title) ? "challenging" : "balanced";
}

function studyMinutes(book: OpenScienceBook): number {
  return Math.max(30, Math.ceil(book.pageCount * 1.5));
}

function attributionLine(book: OpenScienceBook): string {
  return [book.author, book.institution].filter(Boolean).join(" · ");
}

function authorLine(book: OpenScienceBook): string {
  const attribution = attributionLine(book);
  return attribution ? `${book.title} by ${attribution}` : book.title;
}

function courseDescription(book: OpenScienceBook): string {
  return `Read ${authorLine(book)} as an open ${book.subject} resource. ${book.pageCount} pages · ${book.license}. Use the orientation lesson to open the full text and verify the source attribution.`;
}

